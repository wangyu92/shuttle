// Device info and the results note (markdown table + JSON).
import { Platform, apiVersion } from "obsidian";
import type { ProbeResult } from "./types.js";

export function deviceInfo(deviceName: string): Record<string, unknown> {
  const ua = navigator.userAgent;
  const appVersion = /obsidian\/([\d.]+)/i.exec(ua)?.[1] ?? null;
  const nav = navigator as Navigator & { deviceMemory?: number };
  const p = Platform as unknown as Record<string, unknown>;
  const flags: Record<string, boolean> = {};
  for (const k of Object.keys(p)) if (typeof p[k] === "boolean") flags[k] = p[k] as boolean;
  return {
    deviceName,
    platform: flags,
    userAgent: ua,
    appVersion: appVersion ?? "unknown (not in the user agent)",
    apiVersion,
    navigatorPlatform: navigator.platform,
    hardwareConcurrency: navigator.hardwareConcurrency ?? null,
    deviceMemoryGB: nav.deviceMemory ?? null,
    screen: `${screen.width}x${screen.height}@${window.devicePixelRatio}`,
    language: navigator.language,
    timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone,
    isSecureContext: globalThis.isSecureContext === true,
    origin: globalThis.location?.origin ?? null,
  };
}

const cell = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

export function renderNote(device: Record<string, unknown>, results: ProbeResult[], enrollUri: string): string {
  const order = (id: string) => {
    const m = /^(M|P0-C)(\d+)/.exec(id);
    return m ? (m[1] === "M" ? 0 : 1000) + Number(m[2]) : 5000;
  };
  const sorted = [...results].sort((a, b) => order(a.id) - order(b.id) || a.id.localeCompare(b.id));
  const lines: string[] = [];
  lines.push(`# Shuttle spike results: ${cell(device.deviceName)}`, "");
  lines.push("Generated by the Shuttle Spike test plugin (design §7.9, §10.2). Test vault only.", "");
  lines.push("| Device | |", "|---|---|");
  for (const k of ["deviceName", "appVersion", "apiVersion", "userAgent", "navigatorPlatform", "screen", "hardwareConcurrency", "deviceMemoryGB", "isSecureContext"]) {
    lines.push(`| ${k} | ${cell(device[k])} |`);
  }
  const flags = device.platform as Record<string, boolean>;
  lines.push(`| Platform | ${cell(Object.entries(flags).filter(([, v]) => v).map(([k]) => k).join(", "))} |`, "");
  lines.push("| ID | Probe | Status | Summary | ms | At |", "|---|---|---|---|---|---|");
  for (const r of sorted) lines.push(`| ${cell(r.id)} | ${cell(r.title)} | ${r.status.toUpperCase()} | ${cell(r.summary)} | ${r.ms} | ${r.at.slice(11, 19)} |`);
  lines.push("", `M19 test link: [shuttle-enroll](${enrollUri}) and \`${enrollUri}\``, "");
  lines.push("```json", JSON.stringify({ device, results: sorted }, null, 2), "```", "");
  return lines.join("\n");
}
